/**
 * Snapshot the markets-hero flow contracts into this repo (plan-v2-ui §3):
 *   lib/v2/flows.json   every flow.json, in journey order, with the source commit
 *   docs/v2-parity.md   one row per state with its parity status (lib/v2/status.json)
 * Run after pulling markets-hero: `npm run v2:sync`. It only READS the sibling repo.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const HERO = resolve(process.env.MARKETS_HERO_DIR ?? join(process.cwd(), '..', 'markets-hero'));
const read = <T>(p: string): T => JSON.parse(readFileSync(p, 'utf8')) as T;

interface Order {
  flows: string[];
  groups: { name: string; flows: string[] }[];
}
interface RawFlow {
  id: string;
  title: string;
  summary: string;
  shell: string;
  default: string;
  states: { id: string; label: string; note?: string; screenshot?: boolean }[];
  exits: { on: string; to: string; state: string }[];
  events: { name: string; when: string }[];
}

const order = read<Order>(join(HERO, 'ux', 'flows.json'));
const sourceCommit = execFileSync('git', ['-C', HERO, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();

const flows = order.flows.map((id) => {
  const f = read<RawFlow>(join(HERO, 'ux', 'flows', id, 'flow.json'));
  return {
    id: f.id,
    title: f.title,
    summary: f.summary,
    shell: f.shell,
    default: f.default,
    group: order.groups.find((g) => g.flows.includes(id))?.name ?? '',
    states: f.states.map((s) => ({ id: s.id, label: s.label, note: s.note ?? '', screenshot: s.screenshot !== false })),
    exits: f.exits,
    events: f.events,
  };
});

writeFileSync(join('lib', 'v2', 'flows.json'), `${JSON.stringify({ sourceCommit, flows }, null, 2)}\n`);

const status = read<Record<string, string>>(join('lib', 'v2', 'status.json'));
const total = flows.reduce((n, f) => n + f.states.length, 0);
const count = (s: string) => flows.reduce((n, f) => n + f.states.filter((x) => (status[`${f.id}:${x.id}`] ?? 'todo') === s).length, 0);
const lines = [
  '# v2 parity table',
  '',
  `Generated by \`npm run v2:sync\` from markets-hero @ ${sourceCommit}. Status lives in \`lib/v2/status.json\``,
  '(`todo` → `lab` matches the screenshot from fixtures → `wired` real data → `done` motion checklist walked).',
  '',
  `**${total} states** · done ${count('done')} · wired ${count('wired')} · lab ${count('lab')} · todo ${count('todo')}`,
  '',
];
for (const f of flows) {
  lines.push(`## ${f.id} — ${f.title} (${f.shell} shell)`, '', '| State | Label | Screenshot | Status |', '|---|---|---|---|');
  for (const s of f.states) {
    lines.push(`| \`${s.id}\` | ${s.label} | ${s.screenshot ? 'desktop + mobile' : 'none'} | ${status[`${f.id}:${s.id}`] ?? 'todo'} |`);
  }
  lines.push('', `Exits: ${f.exits.map((x) => `\`${x.to}:${x.state}\``).join(' · ') || 'none'}`);
  lines.push(`Events: ${f.events.map((e) => `\`${e.name}\``).join(' · ') || 'none'}`, '');
}
writeFileSync(join('docs', 'v2-parity.md'), `${lines.join('\n')}\n`);
console.log(`[v2-sync] ${flows.length} flows, ${total} states from markets-hero @ ${sourceCommit}`);
